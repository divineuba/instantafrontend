export type IconName = keyof typeof iconMap;

export function Icon({
  name,
  size = 16,
  strokeWidth = 1.5,
  ...props
}: { name: IconName } & LucideProps) {
  const Comp = iconMap[name];
  return <Comp size={size} strokeWidth={strokeWidth} {...props} />;
}
